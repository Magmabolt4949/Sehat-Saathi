export function t(lang: LanguageCode, key: TranslationKey, vars?: Record<string, string>): string {
  const template = translations[lang]?.[key] ?? translations.en[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => vars[name] ?? "");
}

export function getLanguage(code: string | undefined | null): LanguageOption {
  return LANGUAGES.find((l) => l.code === code) ?? LANGUAGES[0];
}

const LANGUAGE_STORAGE_KEY = "sehat-saathi-language";

/** Last language the user picked, persisted so other routes (e.g. /appointments) open in it too. */
export function getSavedLanguage(): LanguageCode {
  if (typeof window === "undefined") return "en";
  try {
    return getLanguage(window.localStorage.getItem(LANGUAGE_STORAGE_KEY)).code;
  } catch {
    return "en";
  }
}

export function saveLanguage(code: LanguageCode) {
  if (typeof window === "undefined") return;
  try {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, code);
  } catch {
    // Ignore write failures (private browsing, storage quota, etc.) — non-critical.
  }
}
